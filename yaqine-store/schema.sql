CREATE TABLE IF NOT EXISTS products (
  id TEXT PRIMARY KEY, name TEXT NOT NULL, price INTEGER NOT NULL DEFAULT 0,
  category TEXT NOT NULL DEFAULT 'Homme', description TEXT NOT NULL DEFAULT '',
  sold_out INTEGER NOT NULL DEFAULT 0, image TEXT NOT NULL, size TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS orders (
  id TEXT PRIMARY KEY, day TEXT NOT NULL, product_id TEXT, product_name TEXT NOT NULL, size TEXT NOT NULL DEFAULT '',
  price INTEGER NOT NULL, qty INTEGER NOT NULL, name TEXT NOT NULL, phone TEXT NOT NULL, wilaya TEXT NOT NULL, note TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'new'
);
CREATE TABLE IF NOT EXISTS events (day TEXT NOT NULL, vid TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS ev_day ON events(day);
CREATE INDEX IF NOT EXISTS or_day ON orders(day);
CREATE TABLE IF NOT EXISTS settings (key TEXT PRIMARY KEY, value TEXT NOT NULL DEFAULT '');
